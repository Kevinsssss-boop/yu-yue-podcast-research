# 显示顺序：从「最专门」到「最泛」
ORDER = ['语言教学', '社会人文', '自我成长', '商业科技',
         '故事虚构', '影视娱乐音乐', '儿童亲子', '宗教灵性', '闲聊']


def main():
    prog_path = os.path.join(ROOT, '02-清洗后数据', '节目表_粤语.csv')
    progs = [r for r in csv.DictReader(open(prog_path, encoding='utf-8-sig'))
             if r['平台'] == '喜马拉雅']

    missing = [r['节目名'] for r in progs if r['节目名'] not in TOPIC]
    extra = [k for k in TOPIC if k not in {r['节目名'] for r in progs}]

    print(f'喜马拉雅节目：{len(progs)}　已标：{len(progs) - len(missing)}')
    if missing:
        print('⚠️ 没标的：')
        for m in missing:
            print('   ', m)
    if extra:
        print('⚠️ 标注表里有、数据里没有的：')
        for m in extra:
            print('   ', m)

    # 写出
    p_out = os.path.join(OUTDIR, '内容主题_定稿.csv')
    rows = []
    for r in progs:
        t = TOPIC.get(r['节目名'], '未标注')
        rows.append({
            '节目名': r['节目名'],
            '主题': t,
            '形态_旧': r['内容形态'],
            '集数': r['集数'],
        })
    rows.sort(key=lambda x: (ORDER.index(x['主题']) if x['主题'] in ORDER else 99,
                             -int(x['集数'] or 0)))
    with open(p_out, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=['节目名', '主题', '形态_旧', '集数'])
        w.writeheader()
        w.writerows(rows)
    print(f'\n[OK] {p_out}')

    # 分组打印
    print()
    print('=' * 70)
    print(' 按主题分组')
    print('=' * 70)
    by = defaultdict(list)
    for r in rows:
        by[r['主题']].append(r)
    cnt = Counter(r['主题'] for r in rows)
    for t in ORDER:
        members = by.get(t, [])
        pct = len(members) / len(rows) * 100
        print(f'\n【{t}】{len(members)} 个（{pct:.1f}%）')
        if not members:
            print('    （喜马拉雅样本里没有）')
        for m in members:
            print(f"    {int(m['集数'] or 0):>5}集  {m['节目名'][:38]}")


if __name__ == '__main__':
    main()
