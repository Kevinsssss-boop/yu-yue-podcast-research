def _borders(tbl):
    tblPr = tbl._tbl.tblPr
    b = OxmlElement('w:tblBorders')
    for edge in ('top', 'bottom'):
        e = OxmlElement(f'w:{edge}')
        e.set(qn('w:val'), 'single')
        e.set(qn('w:sz'), '12')
        e.set(qn('w:color'), '16365C')
        b.append(e)
    for edge in ('left', 'right', 'insideH', 'insideV'):
        e = OxmlElement(f'w:{edge}')
        e.set(qn('w:val'), 'none')
        b.append(e)
    tblPr.append(b)
    for c in tbl.rows[0].cells:
        tcPr = c._tc.get_or_add_tcPr()
        tcb = OxmlElement('w:tcBorders')
        e = OxmlElement('w:bottom')
        e.set(qn('w:val'), 'single')
        e.set(qn('w:sz'), '6')
        e.set(qn('w:color'), '16365C')
        tcb.append(e)
        tcPr.append(tcb)


def table(doc, headers, rows, cap=None, size=TBL, first_left=True, after=12):
    if cap:
        tblcap(doc, cap)
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = True
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        _clear_spacing(p)
        set_font(p.add_run(str(h)), cn='黑体', size=size, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            p = cells[i].paragraphs[0]
            p.alignment = (WD_ALIGN_PARAGRAPH.LEFT if (i == 0 and first_left)
                           else WD_ALIGN_PARAGRAPH.CENTER)
            _clear_spacing(p)
            set_font(p.add_run(str(v)), size=size)
    _borders(t)
    # Word 要求表格后面必须有一个段落，否则两张表会贴在一起。
    # 这里把它压成 1pt 高、1pt 字号的隐形段，看起来就是表格下方的留白，
    # 而不是一条空行。
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(0)
    pf.space_after = Pt(after)
    pf.line_spacing = Pt(1)          # 固定行高 1pt
    pPr = p._p.get_or_add_pPr()
    rPr = OxmlElement('w:rPr')
    for tag, val in (('w:sz', '2'), ('w:szCs', '2')):
        e = OxmlElement(tag)
        e.set(qn('w:val'), val)
        rPr.append(e)
    pPr.append(rPr)
    return t


def toc(doc):
    p = doc.add_paragraph()
    r = p.add_run()
    for tag, val in (('begin', None), (None, r'TOC \o "1-3" \h \z \u'),
                     ('separate', None), (None, 'TOC_PLACEHOLDER')):
        if tag:
            e = OxmlElement('w:fldChar')
            e.set(qn('w:fldCharType'), tag)
            r._r.append(e)
        else:
            e = OxmlElement('w:instrText' if val.startswith('TOC') else 'w:t')
            e.set(qn('xml:space'), 'preserve')
            e.text = val
            r._r.append(e)
    e = OxmlElement('w:fldChar')
    e.set(qn('w:fldCharType'), 'end')
    r._r.append(e)


def page_number(doc):
    p = doc.sections[0].footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run()
    for tag, val in (('begin', None), (None, 'PAGE'), ('end', None)):
        if tag:
            e = OxmlElement('w:fldChar')
            e.set(qn('w:fldCharType'), tag)
            r._r.append(e)
        else:
            e = OxmlElement('w:instrText')
            e.set(qn('xml:space'), 'preserve')
            e.text = val
            r._r.append(e)
    set_font(r, size=10)


def setup(doc):
    s = doc.sections[0]
    s.page_width, s.page_height = Cm(21.0), Cm(29.7)
    s.top_margin = s.bottom_margin = Cm(2.54)
    s.left_margin = s.right_margin = Cm(3.0)
    st = doc.styles['Normal']
    st.font.name = 'Times New Roman'
    st.font.size = Pt(TXT)
    st.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')


