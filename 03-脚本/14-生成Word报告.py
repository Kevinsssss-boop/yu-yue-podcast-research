def set_font(run, cn='宋体', en='Times New Roman', size=12,
             bold=False, color=None, italic=False):
    run.font.name = en
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color:
        run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), cn)
    rFonts.set(qn('w:ascii'), en)
    rFonts.set(qn('w:hAnsi'), en)


def heading(doc, text, level):
    """用内置 Heading 样式，保证目录能抓到。"""
    p = doc.add_heading('', level=level)
    run = p.add_run(text)
    cfg = {1: ('黑体', 16, 18, 10),
           2: ('黑体', 14, 14, 8),
           3: ('黑体', 12, 10, 6)}[level]
    set_font(run, cn=cfg[0], en='Arial', size=cfg[1], bold=True,
             color=RGBColor(0, 0, 0))
    p.paragraph_format.space_before = Pt(cfg[2])
    p.paragraph_format.space_after = Pt(cfg[3])
    p.paragraph_format.line_spacing = 1.4
    return p


def para(doc, text, indent=True, size=12, bold=False, align=None,
         space_after=6, line_spacing=1.5):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = line_spacing
    pf.space_after = Pt(space_after)
    if indent:
        pf.first_line_indent = Pt(size * 2)
    if align is not None:
        p.alignment = align
    r = p.add_run(text)
    set_font(r, size=size, bold=bold)
    return p


def caption(doc, text, before=6, after=12):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    r = p.add_run(text)
    set_font(r, cn='黑体', size=10.5)
    return p


